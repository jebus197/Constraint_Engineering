#!/usr/bin/env python3
"""ITEM 1 of his plan: set the severity bounds from the ARCHIVE, not a paid run.

HIS RULING, 2026-11-01, verbatim: *"Use the archive to set the severity bounds.
9-14 simulated runs would take days. But I think you should do at least one
simulated run once these bounds are set to check that the new severity mechanics
work as expected and matches expectations."*

THE TRUTH SIGNAL IS PROGRAMMATIC, NOT A VOTE. `falsifier_verdict` is written by
running a falsifier, and it is present on 735 entries across 17 real-seat runs.
`status` is NOT used here: CONFIRMED/REFUTED in that field is derived partly from
model CONFIRM votes, and the standing rule is that findings are confirmed
programmatically or by HIL, never by model voting. `status_adjudicator` would be
ideal and reaches only 20 entries in 2 runs, which is too thin.

WHAT THE ARCHIVE CAN AND CANNOT GIVE, stated because conflating them is how a
severity bound gets set on the wrong quantity:

  CAN: the DISCRIMINATION of the severity proxy -- whether a finding the
       falsifier confirmed carried a higher severity than one it refuted. This
       is a precision-side question and the archive answers it directly.
  CANNOT: the per-seat DETECTION POWER d_i, which is a RECALL quantity. The
       archive never records a flaw nobody raised, so recall is not estimable
       from raised findings alone. Capture-recapture over the multi-seat overlap
       is the method that would reach it, and it is NOT attempted here.

THIS SETTLES WHAT THE 2026-09-02 AUDIT COULD NOT. That audit's severities lay in
[0.65, 0.74] ONLY, a window 0.09 wide, and the standing correction of 2026-10-28
records its power against even a strong relationship as 0.144250 -- so its
kappa = -0.022688 was UNINFORMATIVE about the proxy rather than negative about
it. Real runs span the full [0.00, 1.00].

INTERVAL DISCIPLINE. An AUC's natural Wilson interval over n1*n2 PAIRS is wrong:
the pairs are generated by n1+n2 findings and are not independent. A first
version of this measurement printed [0.792279, 0.809291] on that basis. The
honest interval bootstraps the FINDINGS and is 17.9 times wider. Both are
reported so the error cannot come back silently.
"""
from __future__ import annotations

import argparse
import json
import pathlib
import statistics

import numpy as np
from scipy import stats
from statsmodels.stats.proportion import proportion_confint

REPO = pathlib.Path(__file__).resolve().parents[1]
LOGS = REPO / "bench" / "logs"

#: The cut the live gate uses. Named here so a change to it fails this script's
#: guard rather than silently invalidating the comparison below.
LIVE_CRITICAL_CUT = 0.7

DECIDED = ("CONFIRMED", "REFUTED")


def real_runs():
    """Real-seat runs only. A seat name carrying `sim` is a simulation seat."""
    for d in sorted(LOGS.iterdir()):
        st = d / "runner_state.json"
        if not st.is_file():
            continue
        try:
            s = json.loads(st.read_text())
        except Exception:                                   # noqa: BLE001
            continue
        seats = sorted(s.get("raw_counts_per_model") or {})
        if not seats or any("sim" in x.lower() for x in seats):
            continue
        yield d.name, s


def decided_findings() -> tuple[list, list, dict]:
    """Severities split by the FALSIFIER's verdict, plus what was undecidable."""
    conf, refu = [], []
    other = {"no falsifier run": 0, "ERROR": 0, "UNTOOLABLE": 0}
    for _, s in real_runs():
        ents = (s.get("registry") or {}).get("entries") or {}
        for it in (ents.values() if isinstance(ents, dict) else ents):
            sev = it.get("severity")
            v = str(it.get("falsifier_verdict") or "")
            if not isinstance(sev, (int, float)):
                continue
            if v == "CONFIRMED":
                conf.append(float(sev))
            elif v == "REFUTED":
                refu.append(float(sev))
            elif v in ("ERROR", "UNTOOLABLE"):
                other[v] += 1
            else:
                other["no falsifier run"] += 1
    return conf, refu, other


def auc(a: np.ndarray, b: np.ndarray) -> float:
    u = stats.mannwhitneyu(a, b, alternative="greater").statistic
    return float(u / (len(a) * len(b)))


def main() -> int:
    ap = argparse.ArgumentParser(
        prog="the_severity_bounds_from_the_archive_2026-11-01.py",
        description="Set the severity bounds from the archived real-seat runs. "
                    "Reads only; writes nothing; exits non-zero if a check fails.")
    ap.parse_args()

    conf, refu, other = decided_findings()
    c, r = np.array(conf), np.array(refu)
    fails: list[str] = []

    print("=" * 74)
    print("PART 1. THE POPULATION, AND WHAT WAS UNDECIDABLE")
    print("=" * 74)
    print(f"  falsifier CONFIRMED : {len(c):5d}")
    print(f"  falsifier REFUTED   : {len(r):5d}")
    for k, n in other.items():
        print(f"  {k:19s} : {n:5d}   (verified nothing; excluded)")
    assert len(c) > 100 and len(r) > 5, "too few decided findings to bound anything"
    print(f"  severity range covered: [{min(c.min(), r.min()):.2f}, "
          f"{max(c.max(), r.max()):.2f}]  against the 2026-09-02 audit's "
          f"[0.65, 0.74]")

    print()
    print("=" * 74)
    print("PART 2. DOES SEVERITY DISCRIMINATE? YES, AND THIS IS THE BOUND-SETTER")
    print("=" * 74)
    print(f"  CONFIRMED  mean={c.mean():.6f}  median={np.median(c):.4f}  "
          f"sd={c.std(ddof=1):.6f}")
    print(f"  REFUTED    mean={r.mean():.6f}  median={np.median(r):.4f}  "
          f"sd={r.std(ddof=1):.6f}")
    pu = stats.mannwhitneyu(c, r, alternative="greater").pvalue
    pt = stats.ttest_ind(c, r, equal_var=False).pvalue
    print(f"  Mann-Whitney one-sided p = {pu:.6e}")
    print(f"  Welch t-test       p = {pt:.6e}   (2nd tool, same direction)")

    point = auc(c, r)
    rng = np.random.default_rng(20261101)
    boots = np.array([auc(rng.choice(c, len(c), True), rng.choice(r, len(r), True))
                      for _ in range(20000)])
    blo, bhi = np.percentile(boots, [2.5, 97.5])
    n1, n2 = len(c), len(r)
    q1, q2 = point / (2 - point), 2 * point ** 2 / (1 + point)
    se = float(np.sqrt((point * (1 - point) + (n1 - 1) * (q1 - point ** 2)
                        + (n2 - 1) * (q2 - point ** 2)) / (n1 * n2)))
    z = stats.norm.ppf(0.975)
    wlo, whi = proportion_confint(int(round(point * n1 * n2)), n1 * n2,
                                  alpha=0.05, method="wilson")
    print(f"\n  AUC = {point:.6f}")
    print(f"    bootstrap over FINDINGS  95% [{blo:.6f}, {bhi:.6f}]   <-- QUOTE THIS")
    print(f"    Hanley-McNeil closed form 95% [{point - z * se:.6f}, "
          f"{point + z * se:.6f}]")
    print(f"    WRONG, over PAIRS         95% [{wlo:.6f}, {whi:.6f}]   "
          f"{(bhi - blo) / (whi - wlo):.1f}x too narrow -- kept to name the error")
    lower = min(blo, point - z * se)
    if lower <= 0.5:
        fails.append(f"the conservative AUC lower bound is {lower:.6f}, at or below "
                     f"chance, so severity does NOT discriminate and no bound "
                     f"derived from it may be used")
    print(f"  discriminates, conservative lower bound {lower:.6f} > 0.5: "
          f"{lower > 0.5}")

    print()
    print("=" * 74)
    print("PART 3. WHERE THE LIVE 0.7 CUT SITS, AND WHAT THE ARCHIVE WOULD CHOOSE")
    print("=" * 74)
    cuts = np.round(np.arange(0.05, 1.00, 0.05), 2)
    best = None
    print(f"  {'cut':>6} {'sens':>8} {'spec':>8} {'Youden J':>9}")
    for cut in cuts:
        sens = float((c >= cut).mean())             # confirmed correctly flagged
        spec = float((r < cut).mean())              # refuted correctly not flagged
        j = sens + spec - 1
        if best is None or j > best[3]:
            best = (float(cut), sens, spec, j)
        if abs(cut - LIVE_CRITICAL_CUT) < 1e-9 or cut in (0.3, 0.5, 0.8, 0.9):
            print(f"  {cut:>6.2f} {sens:>8.4f} {spec:>8.4f} {j:>9.4f}"
                  + ("   <-- THE LIVE CUT" if abs(cut - LIVE_CRITICAL_CUT) < 1e-9 else ""))
    print(f"\n  Youden-optimal cut on the archive: {best[0]:.2f} "
          f"(sens {best[1]:.4f}, spec {best[2]:.4f}, J {best[3]:.4f})")
    live_sens = float((c >= LIVE_CRITICAL_CUT).mean())
    live_spec = float((r < LIVE_CRITICAL_CUT).mean())
    print(f"  the LIVE cut {LIVE_CRITICAL_CUT}: sens {live_sens:.4f}, "
          f"spec {live_spec:.4f}, J {live_sens + live_spec - 1:.4f}")
    print(f"  J lost by keeping {LIVE_CRITICAL_CUT} instead of {best[0]:.2f}: "
          f"{best[3] - (live_sens + live_spec - 1):.4f}")
    print()
    print("  THIS IS NOT A RECOMMENDATION TO MOVE THE CUT. Moving it changes what")
    print("  the gate calls CRITICAL, which is a decision reserved to him, and the")
    print("  Youden point is optimal for a 1:1 cost of the 2 error kinds -- a")
    print("  premise nothing here establishes. It is reported so the cost of the")
    print("  present cut is on the record rather than assumed to be zero.")

    print()
    print("=" * 74)
    print("PART 4. THE BOUND THE RECURSION ACTUALLY NEEDS, AND WHAT IS STILL OWED")
    print("=" * 74)
    print("  SET FROM THE ARCHIVE, usable now:")
    print(f"    severity is a VALID ordering signal: AUC {point:.4f}, conservative")
    print(f"    lower bound {lower:.4f}, so a severity-ordered gate is better than")
    print("    arbitrary on real data. That is what the shadow arm needs to run.")
    print("  NOT SET, AND NAMED RATHER THAN GUESSED:")
    print("    d_i, the per-seat detection power, is RECALL and is not estimable")
    print("    from raised findings. Capture-recapture over the multi-seat overlap")
    print("    is the route; it is the next measurement, not this one.")
    print("    nu, the re-injection rate, needs a finding attributable to an")
    print("    earlier fix. `open_since_round > 0` is a CANDIDATE proxy and was")
    print("    NOT used: a finding first seen in a later round may simply have")
    print("    been found late. Choosing that proxy without measuring its")
    print("    alternatives is this project's single most recorded error class.")

    print()
    print("=" * 74)
    print(f"FAILURES: {len(fails)}")
    for f in fails:
        print("  -", f)
    return 1 if fails else 0


if __name__ == "__main__":
    raise SystemExit(main())
