"""How many items remain on the master task list, and is its exhaustion estimable?

HIS QUESTION, 2026-11-09, verbatim: *"But you recently made a measurement that implied
that the master task list might never meaningfully exhaust itself? Logically that doesn't
make sense, because the task list, as stated by me (as in ites I have told you to add to
it), is very much finite. But what I think I you are implying is that given the rate at
which I (as in me/the HIL) add tasks to the mater task list, it cannot be measured
reliably yet, if/when the list will exhaust? That is clearly the more logical
perspective. But lets pin a number on it. Given the items I have told you to add to the
master task list how many items on it, including these 12 issues remain exactly?"*

HE IS RIGHT AND THIS SCRIPT IS WHERE THAT IS SETTLED RATHER THAN ASSERTED. The strong
claim -- that the list never exhausts -- is a claim about a STRUCTURAL property and
nothing here supports it. The weak claim -- that the exhaustion date is not yet
estimable from the observed arrival and closure rates -- is a claim about an INTERVAL,
and an interval can be computed and can fail to exclude anything. This script computes
it and reports which of the 2 the evidence supports.

WHAT IT MEASURES, in 3 parts.

  1. THE EXACT CENSUS, now. Every entry, its state, and -- for every OPEN entry --
     whether it carries a `ruled` date. That field is the whole crux of his complaint:
     an entry he HAS ruled on but which carries no ruled date is regenerated by the
     decisions surface as though it were awaiting him, so he is shown his own rulings
     back as pending work. The census separates "awaiting him" from "awaiting me".

  2. THE DAILY TIME SERIES, from git. The last commit of each calendar day that touched
     the list, with the entry total and the open count at that commit. Arrival is the
     daily increase in the total; closure is the daily increase in the resolved count.
     Nothing here is typed: every point is recomputed from the file as it stood at that
     commit, by the SAME canonical reader the live census uses, so the series and the
     census cannot drift apart.

  3. THE EXHAUSTION ESTIMATE, or an honest refusal to give one. Ordinary least squares
     of open-count against day index, slope with a 95% interval on 2 independent routes
     (scipy.stats.linregress and a NumPy normal-equations solve with its own standard
     error). If the slope interval contains 0 or is positive, NO exhaustion date is
     computable and the script says so in those words. If it is negative throughout,
     the projected date is reported WITH the interval implied by the slope bounds,
     because a point estimate from a noisy slope is exactly the kind of figure this
     project has had to withdraw before.

WHY A SCRIPT AT ALL: `measured-rate-travels-with-its-script`. Every number in this
file's output is reproduced by running it. The 12 figures quoted to him on 2026-11-09
before this existed were read off a generated document, which is a claim about evidence
rather than evidence.

Exit code 0 always: this is a measurement, not a gate. It prints what it finds.
"""
