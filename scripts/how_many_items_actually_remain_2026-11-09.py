    assert sum(by_state.values()) == len(entries), "state census does not close"
    print(f"   states sum to total: {sum(by_state.values())} == {len(entries)}  OK")

    print("\n== 2. THE OPEN ENTRIES, SPLIT BY WHOSE MOVE IT IS ==")
