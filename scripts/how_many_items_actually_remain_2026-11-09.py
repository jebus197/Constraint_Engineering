def _iv(k: int, n: int):
    """Wilson and Clopper-Pearson, each on 2 INDEPENDENT routes."""
    from scipy import stats
    from statsmodels.stats.proportion import proportion_confint
    import mpmath
    mpmath.mp.dps = 40
    if n == 0:
        return (0.0, 1.0), (0.0, 1.0), 0.0
    wl, wh = proportion_confint(k, n, alpha=0.05, method="wilson")
    z = stats.norm.ppf(0.975)
    p = k / n
    d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d
    hw = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    wdiff = max(abs(wl - (c - hw)), abs(wh - (c + hw)))
    cl = 0.0 if k == 0 else float(stats.beta.ppf(0.025, k, n - k + 1))
    ch = 1.0 if k == n else float(stats.beta.ppf(0.975, k + 1, n - k))

    def bi(a, b, y):
        """Invert the regularised incomplete beta by bisection.

        HARDENED 2026-11-04. `mpmath.betainc` is fast, but its hyp2f1 path
        FAILS TO CONVERGE for large parameters at mid-range x. Measured at
        a=2437, b=17564 it succeeds for x <= 0.1264 and for x >= 0.9 and raises
        ValueError in between -- which is exactly where a bisection over [0, 1]
        takes its first step, so the whole inversion died rather than degrading.
        It surfaced when a producer called this at k=2436, n=20000; every
        existing caller used a small n, and the guard that executes every `_iv`
        against the same k and n uses n <= 38, so no test could have seen it.

        Where betainc raises, the same integral is computed by quadrature in
        log space instead. At the measured failing point that agreed with
        scipy's quantile to 1.11e-16. It costs about 6 s per bound against
        milliseconds for betainc, so it is used only after a failure, never by
        default.
        """
        logB = mpmath.log(mpmath.beta(a, b))

        def by_quad(x):
            if x <= 0:
                return mpmath.mpf(0)
            def dens(u):
                return mpmath.e**((a - 1) * mpmath.log(u)
                                  + (b - 1) * mpmath.log1p(-u) - logB)
            return mpmath.quad(dens, [0, min(mpmath.mpf(x), mpmath.mpf(1))])

        fell_back = False

        def f(x):
            nonlocal fell_back
            if not fell_back:
                try:
                    return mpmath.betainc(a, b, 0, x, regularized=True) - y
                except Exception:
                    fell_back = True
            return by_quad(x) - y

        # STOP ON PRECISION, not on a fixed count. The bracket halves every
        # step, so 2**-60 is already below this tolerance and a fixed 240 did
        # 180 redundant evaluations. That is free for betainc and it is NOT
        # free for the quadrature fallback, which costs about 28 ms per
        # evaluation: 240 steps took 6.66 s and 60 take 1.69 s for a bound
        # identical to 12 decimal places. The count is still capped so a
        # pathological case cannot spin.
        lo, hi = mpmath.mpf(0), mpmath.mpf(1)
        tol = mpmath.mpf("1e-18")
        for _ in range(240):
            if hi - lo < tol:
                break
            m = (lo + hi) / 2
            lo, hi = (m, hi) if f(m) < 0 else (lo, m)
        return float((lo + hi) / 2)

    cdiff = max(abs(cl - (0.0 if k == 0 else bi(k, n - k + 1, 0.025))),
                abs(ch - (1.0 if k == n else bi(k + 1, n - k, 0.975))))
    return (max(0.0, wl), wh), (cl, ch), max(wdiff, cdiff)


_MARKERS_CACHE = None


def _markers():
    """The canonical reader, loaded by path so this script has no import-order needs.

    TWO NON-OBVIOUS REQUIREMENTS, both found by execution rather than by reading.

    1. THE MODULE MUST BE IN `sys.modules` BEFORE `exec_module` RUNS. `task_list_markers`
       defines an `@dataclass`, and `dataclasses._is_type` resolves the decorated class's
       `__module__` through `sys.modules`. For a module loaded by path and not yet
       registered, that lookup returns None and the decorator dies with
       `AttributeError: 'NoneType' object has no attribute '__dict__'` -- a message that
       says nothing about the real cause. Registering first is the whole fix.

    2. IT IS CACHED. `_count_at` is called once per calendar day in the history, so an
       uncached loader would re-execute the reader 100-plus times for no gain.
    """
    global _MARKERS_CACHE
    if _MARKERS_CACHE is not None:
        return _MARKERS_CACHE
    spec = importlib.util.spec_from_file_location(
        "task_list_markers", REPO / "scripts" / "task_list_markers.py")
    mod = importlib.util.module_from_spec(spec)
    sys.modules["task_list_markers"] = mod      # BEFORE exec_module -- see note 1
    spec.loader.exec_module(mod)
    _MARKERS_CACHE = mod
    return mod


def _git(*args: str) -> str:
    return subprocess.run(["git", "-C", str(REPO), *args],
                          capture_output=True, text=True, timeout=300).stdout


def census():
    """The exact state of the list right now, by the canonical reader."""
    m = _markers()
    entries = m.parse_entries(REPO / LIST_REL)
    by_state = collections.Counter(e.state or "NO_MARKER" for e in entries)
    open_entries = [e for e in entries if e.state == "OPEN"]
    ruled = [e for e in open_entries if e.ruled]
    unruled = [e for e in open_entries if not e.ruled]
    return entries, by_state, open_entries, ruled, unruled


def _count_at(sha: str) -> tuple[int, int] | None:
    """Entry total and open count as the list stood at `sha`.

    Recomputed by the SAME reader, against a temporary checkout of that one blob, so a
    historical point and the live census cannot be produced by 2 different rules. Returns
    None where the file did not exist at that commit or the reader could not parse it.
    """
    blob = _git("show", f"{sha}:{LIST_REL}")
    if not blob.strip():
        return None
    tmp = pathlib.Path("/tmp") / f"cdsfl_tl_{sha[:12]}" / "experimental_notes"
    tmp.mkdir(parents=True, exist_ok=True)
    f = tmp / "CDSFL_MASTER_TASK_LIST.md"
    f.write_text(blob)
    try:
        m = _markers()
        es = m.parse_entries(f)
        return len(es), sum(1 for e in es if e.state == "OPEN")
    except Exception:
        return None
    finally:
        try:
            f.unlink()
            tmp.rmdir()
            tmp.parent.rmdir()
        except Exception:
            pass


def series():
    """One point per calendar day: the LAST commit of that day touching the list."""
    raw = _git("log", "--follow", "--format=%H|%ad", "--date=short", "--", LIST_REL)
    per_day: dict[str, str] = {}
    order: list[str] = []
    for line in raw.splitlines():
        if "|" not in line:
            continue
        sha, day = line.split("|", 1)
        # git log is newest-first, so the FIRST sha seen for a day is that day's last commit.
        if day not in per_day:
            per_day[day] = sha
            order.append(day)
    pts = []
    for day in sorted(per_day):
        got = _count_at(per_day[day])
        if got is None:
            continue
        total, opn = got
        pts.append((day, total, opn))
    return pts


def slope_two_routes(xs, ys):
    """OLS slope with a 95% interval, computed twice by independent routes."""
    import numpy as np
    from scipy import stats
    x = np.asarray(xs, dtype=float)
    y = np.asarray(ys, dtype=float)
    n = len(x)
    lr = stats.linregress(x, y)
    tcrit = stats.t.ppf(0.975, n - 2)
    a_lo, a_hi = lr.slope - tcrit * lr.stderr, lr.slope + tcrit * lr.stderr

    # Independent route: normal equations, residual variance, standard error from scratch.
    X = np.column_stack([np.ones(n), x])
    beta, *_ = np.linalg.lstsq(X, y, rcond=None)
    resid = y - X @ beta
    s2 = float(resid @ resid) / (n - 2)
    cov = s2 * np.linalg.inv(X.T @ X)
    se2 = float(math.sqrt(cov[1, 1]))
    b_lo, b_hi = beta[1] - tcrit * se2, beta[1] + tcrit * se2

    gap = max(abs(lr.slope - beta[1]), abs(lr.stderr - se2))
    return {
        "slope_scipy": float(lr.slope),
        "slope_numpy": float(beta[1]),
        "stderr_scipy": float(lr.stderr),
        "stderr_numpy": se2,
        "ci_scipy": (float(a_lo), float(a_hi)),
        "ci_numpy": (float(b_lo), float(b_hi)),
        "two_route_gap": gap,
        "intercept": float(beta[0]),
        "r_squared": float(lr.rvalue ** 2),
        "p_value": float(lr.pvalue),
        "n_points": n,
    }


def main() -> int:
    print("=" * 78)
    print("HOW MANY ITEMS ACTUALLY REMAIN -- 2026-11-09")
    print("=" * 78)

    entries, by_state, open_entries, ruled, unruled = census()

    print("\n== 1. THE EXACT CENSUS, by the canonical reader ==")
