    (wl, wh), (cl, ch), gap = _iv(len(ruled), len(open_entries))
    print(f"   share already ruled: {len(ruled)}/{len(open_entries)} = "
          f"{len(ruled)/len(open_entries):.6f}")
    print(f"     Wilson [{wl:.6f}, {wh:.6f}]  Clopper-Pearson [{cl:.6f}, {ch:.6f}]"
          f"  worst 2-route gap {gap:.3e}")

    print("\n   -- OPEN entries WITH a recorded ruling (mine to do) --")
    for e in sorted(ruled, key=lambda e: e.ident):
        title = e.text.lstrip("*- ").strip()[:92]
        print(f"      {e.ident:14s} ruled {e.ruled:12s} status={e.status:10s} {title}")
    print("\n   -- OPEN entries with NO recorded ruling --")
    for e in sorted(unruled, key=lambda e: e.ident):
        title = e.text.lstrip("*- ").strip()[:92]
        print(f"      {e.ident:14s} ruled {'(none)':12s} status={str(e.status):10s} {title}")

    print("\n== 3. THE DAILY TIME SERIES, recomputed from git by the same reader ==")
    pts = series()
    if len(pts) < 4:
        print(f"   only {len(pts)} usable point(s); no trend is estimable")
        return 0
    print(f"   usable_days: {len(pts)}   first {pts[0][0]}   last {pts[-1][0]}")
    d0 = dt.date.fromisoformat(pts[0][0])
    xs = [(dt.date.fromisoformat(d) - d0).days for d, _, _ in pts]
    totals = [t for _, t, _ in pts]
    opens = [o for _, _, o in pts]
    print(f"   entry total: {totals[0]} -> {totals[-1]}   "
          f"open: {opens[0]} -> {opens[-1]}")
    span = xs[-1] or 1
    print(f"   arrival over span: {totals[-1] - totals[0]} entries in {span} days "
          f"= {(totals[-1]-totals[0])/span:.6f}/day")
    resolved = [t - o for t, o in zip(totals, opens)]
    print(f"   closure over span: {resolved[-1] - resolved[0]} resolved in {span} days "
          f"= {(resolved[-1]-resolved[0])/span:.6f}/day")

    print("\n   -- last 21 days, one line each (day, total, open) --")
    for d, t, o in pts[-21:]:
        print(f"      {d}  total={t:4d}  open={o:3d}")

    print("\n== 4. IS AN EXHAUSTION DATE ESTIMABLE? ==")
    fit = slope_two_routes(xs, opens)
    print(f"   OLS of OPEN count against day index, n = {fit['n_points']}")
    print(f"     slope  scipy {fit['slope_scipy']:+.6f}/day   "
          f"numpy {fit['slope_numpy']:+.6f}/day   gap {fit['two_route_gap']:.3e}")
    print(f"     95% CI scipy [{fit['ci_scipy'][0]:+.6f}, {fit['ci_scipy'][1]:+.6f}]")
    print(f"     95% CI numpy [{fit['ci_numpy'][0]:+.6f}, {fit['ci_numpy'][1]:+.6f}]")
    print(f"     r_squared {fit['r_squared']:.6f}   p {fit['p_value']:.6e}")

    # ------------------------------------------------------------------
    # ★ THE LINEAR FIT IS MIS-SPECIFIED HERE AND MUST NOT BE QUOTED ALONE.
    #
    # FOUND BY RUNNING THIS SCRIPT, 2026-11-09, and it contradicts itself in the
    # output above: the endpoint comparison shows closure OUTPACING arrival and the
    # open count FALLING from 49 to 20, while the OLS slope comes back POSITIVE.
    # Both are arithmetically correct. The series is not monotone -- open fell to 3
    # by mid-October, rose to 36 in early November as 2 large annotation batches
    # landed, then fell again -- so a straight line through it is the wrong model
    # and its sign is an artefact of where the single early high point sits.
    #
    # A straight line fitted to a V reports the slope of the chord, not the
    # behaviour. Quoting it as "the open count is rising" would be the
    # true-sentence-wrong-frame failure this project has recorded before.
    #
    # SO 3 INSTRUMENTS ARE REPORTED AND RANKED, not 1:
    #   * the ENDPOINT net rate, which is what "is it burning down" actually asks;
    #   * MANN-KENDALL, a rank test that asks for monotone trend without assuming
    #     a line, so it can return "no monotone trend" where OLS cannot;
    #   * the OLS slope, LABELLED mis-specified, with r-squared as the evidence.
    # ------------------------------------------------------------------
    import numpy as np
    from scipy import stats as _st

    lo, hi = fit["ci_scipy"]
    endpoint_net = (opens[-1] - opens[0]) / span
    tau, mk_p = _st.kendalltau(xs, opens)
    # Independent route for the same rank statistic, so no single call carries it.
    #
    # ★ IT MUST BE TAU-B, NOT (C-D)/(C+D). First written the naive way, the 2 routes
    # disagreed by 6.476e-02 -- far above machine precision -- and the cause was TIES.
    # `xs` are distinct days so they carry none, but `opens` repeats values (22 appears
    # 4 times, 15 twice), and scipy returns the tie-corrected tau-b while the naive form
    # simply drops tied pairs from its denominator. A 2-route check that compares 2
    # DIFFERENT estimators is not a cross-check; it is 2 answers to 2 questions. The
    # tie correction divides by sqrt((n0-n1)(n0-n2)) instead.
    conc = dis = 0
    for i in range(len(opens)):
        for j in range(i + 1, len(opens)):
            s = np.sign(xs[j] - xs[i]) * np.sign(opens[j] - opens[i])
            if s > 0:
                conc += 1
            elif s < 0:
                dis += 1
    n_obs = len(opens)
    n0 = n_obs * (n_obs - 1) / 2
    n1 = sum(c * (c - 1) / 2 for c in collections.Counter(xs).values())
    n2 = sum(c * (c - 1) / 2 for c in collections.Counter(opens).values())
    denom = math.sqrt((n0 - n1) * (n0 - n2))
    tau_manual = (conc - dis) / denom if denom else 0.0

    # ------------------------------------------------------------------
    # ★ THE DECISIVE INSTRUMENT, AND IT IS NEITHER OF THE 3 BELOW.
    #
    # Both the OLS slope and Mann-Kendall report the open count RISING, while the
    # endpoint comparison reports it FALLING. 2 against 1 is not how this is settled:
    # all 3 are pooling ACROSS A REGIME CHANGE, and this project has already recorded
    # that the pooled figure is the weaker statement -- the Wolfram route-health
    # analysis of 2026-09-10 cut at a fitted change point for exactly this reason and
    # its own note says "do not quote the pooled figure on its own".
    #
    # The 2 regimes here are visible in the raw series: the open count was driven DOWN
    # to its minimum by mid-October, then rose as 2 large annotation batches landed.
    # So the question "does this list exhaust" is not answered by a trend at all. It is
    # answered by whether the count has ever BEEN near zero, because that is a
    # demonstration rather than an extrapolation.
    #
    # The cut is FITTED, not chosen: the split minimising total squared error across 2
    # independent segment means, over every interior candidate.
    # ------------------------------------------------------------------
    best = None
    for c in range(3, len(opens) - 3):
        a, b = opens[:c], opens[c:]
        ma, mb = sum(a) / len(a), sum(b) / len(b)
        sse = sum((v - ma) ** 2 for v in a) + sum((v - mb) ** 2 for v in b)
        if best is None or sse < best[0]:
            best = (sse, c)
    cut = best[1]
    seg1, seg2 = pts[:cut], pts[cut:]
    lo_i = min(range(len(opens)), key=lambda i: opens[i])

    print("\n   -- instrument 0 (DECISIVE): has the list ever approached exhaustion? --")
    print(f"      MINIMUM open count ever recorded: {opens[lo_i]} on {pts[lo_i][0]}")
    print(f"      at that moment the list held {totals[lo_i]} entries, "
          f"{totals[lo_i] - opens[lo_i]} of them resolved")
    print(f"      so the list demonstrably REACHES near-exhaustion: it is not a")
    print(f"      structure that grows without bound, it is a queue that empties")
    print(f"      whenever he stops adding to it.")
    print(f"      fitted change point: {pts[cut][0]} (segment SSE minimised)")
    print(f"      regime 1  {seg1[0][0]} -> {seg1[-1][0]}: open "
          f"{seg1[0][2]} -> {seg1[-1][2]}, mean {sum(o for _,_,o in seg1)/len(seg1):.4f}")
    print(f"      regime 2  {seg2[0][0]} -> {seg2[-1][0]}: open "
          f"{seg2[0][2]} -> {seg2[-1][2]}, mean {sum(o for _,_,o in seg2)/len(seg2):.4f}")

    # The most recent strictly-falling run: the live burn rate, which is the only rate
    # that bears on "how long until this batch is cleared".
    j = len(opens) - 1
    while j > 0 and opens[j - 1] >= opens[j]:
        j -= 1
    if j < len(opens) - 1:
        d_days = xs[-1] - xs[j]
        burn = (opens[j] - opens[-1]) / d_days if d_days else 0.0
        print(f"      CURRENT falling run: {pts[j][0]} -> {pts[-1][0]}, open "
              f"{opens[j]} -> {opens[-1]} = {burn:.6f}/day closed net")
        if burn > 0:
            print(f"      at that rate the remaining {opens[-1]} clear in "
                  f"{opens[-1]/burn:.2f} days -- A RATE OVER "
                  f"{d_days} DAY(S), SO IT IS AN ILLUSTRATION AND NOT A FORECAST.")

    print("\n   -- instrument 1: ENDPOINT NET RATE (what 'burning down' means) --")
    print(f"      open {opens[0]} -> {opens[-1]} over {span} days "
          f"= {endpoint_net:+.6f}/day")
    print(f"      arrival {(totals[-1]-totals[0])/span:+.6f}/day   "
          f"closure {(resolved[-1]-resolved[0])/span:+.6f}/day")
    print(f"      closure EXCEEDS arrival by "
          f"{((resolved[-1]-resolved[0]) - (totals[-1]-totals[0]))/span:+.6f}/day")

    print("\n   -- instrument 2: MANN-KENDALL (monotone trend, no line assumed) --")
    print(f"      kendall tau {tau:+.6f} (scipy)   {tau_manual:+.6f} (pairwise count)"
          f"   gap {abs(tau - tau_manual):.3e}")
    print(f"      p {mk_p:.6e}   concordant {conc}   discordant {dis}")

    print("\n   -- instrument 3: OLS slope, MIS-SPECIFIED, shown for completeness --")
    print(f"      slope {fit['slope_scipy']:+.6f}/day, 95% CI "
          f"[{lo:+.6f}, {hi:+.6f}], r_squared {fit['r_squared']:.6f}")
    print(f"      r_squared {fit['r_squared']:.6f} means "
          f"{1 - fit['r_squared']:.6f} of the variance is NOT a line.")
    sign_conflict = (lo > 0 and endpoint_net < 0) or (hi < 0 and endpoint_net > 0)
    print(f"      sign conflicts with the endpoint rate: {sign_conflict}")
    if sign_conflict:
        print("      ^ THIS IS THE PROOF OF MIS-SPECIFICATION. The 2 disagree in SIGN on")
        print("        the same data, so at most 1 of them describes the series. The")
        print("        endpoint rate is the one that answers the question asked.")

    if sign_conflict or fit["r_squared"] < 0.5:
        verdict = (
            "NO EXHAUSTION DATE IS ESTIMABLE, AND THE REASON IS THE SHAPE OF THE "
            "SERIES RATHER THAN THE SIZE OF THE LIST. The open count is not on a "
            "trend at all: it falls as entries are closed and jumps when a batch of "
            "his annotations lands, so it oscillates rather than trending. On the "
            "endpoint comparison the list IS burning down -- closure outpaces "
            "arrival and the open count fell from "
            f"{opens[0]} to {opens[-1]} -- but the arrival process is his review "
            "schedule, which is not a property of the work and cannot be forecast "
            "from the work. So the LEVEL is reportable and the DATE is not.")
    elif lo < 0 < hi:
        verdict = ("NOT ESTIMABLE. The slope interval CONTAINS 0, so the open count is "
                   "not shown to be falling at all. No exhaustion date follows.")
    elif lo >= 0:
        verdict = ("NOT ESTIMABLE, and the sign is the other way: the open count is "
                   "RISING over this window. No exhaustion date follows.")
